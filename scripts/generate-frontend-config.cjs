// 从 argus/src-tauri/src/config/app.toml 派生前端运行时常量。
// 真相源：app.toml [web].binding / [web].port —— 改配置只改 app.toml，前端 yarn dev / yarn build 自动同步。
// 由 package.json 的 dev / build / tauri:dev / tauri:build 在执行前调用。

const fs = require('node:fs');
const path = require('node:path');

const OUT_PATH = path.join(__dirname, '..', 'src', 'runtime-config.ts');
const TOML_PATH = path.join(__dirname, '..', 'src-tauri', 'src', 'base', 'config', 'app.toml');

function readSection(tomlText, section) {
    const sectionMatch = tomlText.match(new RegExp(`\\[${section}\\]([\\s\\S]*?)(?:\\n\\[|$)`));
    if (!sectionMatch) {
        throw new Error(`[${section}] section missing in app.toml`);
    }
    return sectionMatch[1];
}

function readTomlString(tomlText, section, key) {
    const body = readSection(tomlText, section);
    const lineMatch = body.match(new RegExp(`^\\s*${key}\\s*=\\s*"([^"]*)"`, 'm'));
    if (!lineMatch) {
        throw new Error(`[${section}].${key} missing in app.toml`);
    }
    return lineMatch[1];
}

function readTomlNumber(tomlText, section, key) {
    const body = readSection(tomlText, section);
    const lineMatch = body.match(new RegExp(`^\\s*${key}\\s*=\\s*(\\d+)`, 'm'));
    if (!lineMatch) {
        throw new Error(`[${section}].${key} missing in app.toml`);
    }
    return Number(lineMatch[1]);
}

const tomlText = fs.readFileSync(TOML_PATH, 'utf8');
const binding = readTomlString(tomlText, 'web', 'binding');
const backendPort = readTomlNumber(tomlText, 'web', 'port');
const content =
    `// AUTO-GENERATED by scripts/generate-frontend-config.cjs — DO NOT EDIT.\n` +
    `export const API_BASE_URL = 'http://${binding}:${backendPort}';\n`;

const relativeOut = path.relative(process.cwd(), OUT_PATH);
if (fs.existsSync(OUT_PATH) && fs.readFileSync(OUT_PATH, 'utf8') === content) {
    console.log(
        `[generate-frontend-config] unchanged ${relativeOut} with binding=${binding}, backendPort=${backendPort}`,
    );
} else {
    fs.writeFileSync(OUT_PATH, content, 'utf8');
    console.log(
        `[generate-frontend-config] wrote ${relativeOut} with binding=${binding}, backendPort=${backendPort}`,
    );
}

