export function resolveAiToolId(toolName: string): number | null {
    if (!toolName) {
        return null;
    }
    const toolId = AI_TOOL_NAME_TO_ID[toolName];
    if (!toolId) {
        return null;
    }
    return toolId;
}

export function resolveAiToolLabel(toolName: string): string {
    if (!toolName || !(toolName in AI_TOOL_NAME_TO_ID)) {
        return toolName || translate('common.agent.toolName.unknown');
    }
    return translate(`common.agent.toolName.${toolName}`);
}
